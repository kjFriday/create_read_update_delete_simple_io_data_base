"""Write a mock-data snapshot into every ecosystem project, so each one runs on its own without the hub.

Run after seed.py:  python export_mock.py  [portfolio root, default ..]
Each project gets mock/<table>.json (a JSON list, one row per line), mock/schema.sql (the hub's CREATE TABLE
statements, so its tests can build a database with the exact schema) and mock/README.md. Every slice
keeps its references whole: a ticket's customer and assignee are in the same snapshot. The rows are the
hub's rows, so a program shows the same records whether it reads its snapshot or the shared database.
"""

import json
import os
import random
import sys
from datetime import datetime, timedelta

import db
import lorem
from seed import _mix

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

README = """# mock/

A snapshot of the CRUD hub's seeded data, so this project runs on its own. ACME Inc. and every
person, order and ticket here are fictional; names are random pairs from common-name lists and
free text is lorem ipsum.

Generated by `export_mock.py` in the CRUD hub (after `seed.py`); do not edit by hand.
Same rows and ids as the hub's seeded database, so pointing the program at the shared database shows
the same records. `schema.sql` is the hub's schema, for tests that need a real database.

| File | Rows | Taken from |
|---|---|---|
{rows}
"""


def all_rows(table):
    """Every row, oldest first."""
    return sorted(db.list_rows(table, limit=-1), key=lambda r: r["id"])


def latest(table, n):
    return all_rows(table)[-n:]


def referenced(table, ids):
    ids = {i for i in ids if i is not None}
    return [r for r in all_rows(table) if r["id"] in ids]


def posts(employees, products, n=60):
    """CMS posts (the CMS keeps its own posts table): lorem ipsum, authored by hub employees."""
    out = []
    start = datetime(2026, 1, 5, 9, 0)
    for i in range(n):
        r = random.Random(_mix(0xC35, i))
        title = lorem.sentence(r, 3, 7).rstrip(".")
        if i % 4 == 0:  # every fourth post is about a product
            title = f"{r.choice(products)['name']}: {title.lower()}"
        created = start + timedelta(days=4 * i, minutes=r.randint(0, 600))
        published = r.random() < 0.8
        out.append({
            "id": i + 1,
            "title": title,
            "slug": "-".join(title.lower().replace(":", "").split())[:60].rstrip("-") + f"-{i + 1}",
            "body": {"blocks": [{"type": "paragraph", "text": lorem.paragraph(r, 2, 5)} for _ in range(r.randint(2, 4))]},
            "status": "published" if published else "draft",
            "author_id": r.choice(employees)["id"],
            "published_at": (created + timedelta(hours=2)).isoformat(timespec="minutes") if published else None,
            "created_at": created.isoformat(timespec="minutes"),
        })
    return out


def snapshots():
    employees = all_rows("employees")
    products = all_rows("products")
    tickets = latest("tickets", 400)
    orders = latest("orders", 3000)
    doc_orders = orders[-400:]
    doc_ids = {o["id"] for o in doc_orders}
    documents = [d for d in all_rows("documents") if d["order_id"] in doc_ids]
    events = latest("events", 600)
    staff_ids = {e["id"] for e in employees}

    return {
        "simple_ticket_tracker": {
            "tickets": (tickets, "latest 400 tickets"),
            "customers": (referenced("customers", [t["customer_id"] for t in tickets]), "customers on those tickets"),
            "employees": (employees, "all employees"),
        },
        "data_dash": {
            "orders": (orders, "latest 3000 orders"),
            "products": (products, "all products"),
            "customers": (referenced("customers", [o["customer_id"] for o in orders]), "customers on those orders"),
            "tickets": (tickets, "latest 400 tickets"),
        },
        "document_mover_and_changer": {
            "orders": (doc_orders, "latest 400 orders"),
            "documents": (documents, "documents for those orders"),
            "customers": (referenced("customers", [o["customer_id"] for o in doc_orders]), "customers on those orders"),
            "products": (products, "all products"),
        },
        "notification_and_message_hub": {
            "events": (events, "latest 600 events"),
            "customers": (referenced("customers", [json.loads(e["payload"] or "{}").get("customer_id") for e in events]),
                          "customers named in those events"),
            "employees": ([e for e in employees if e["id"] in staff_ids], "all employees"),
        },
        "content_management_system": {
            "posts": (posts(employees, products), "60 generated posts (CMS-owned, not a hub table)"),
            "employees": (employees, "all employees (post authors)"),
            "products": (products, "all products"),
        },
    }


def write_json(path, rows):
    """One row per line: small diffs when the seed changes, still plain JSON."""
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("[\n" + ",\n".join(json.dumps(r, ensure_ascii=False, sort_keys=True) for r in rows) + "\n]\n")


SCHEMA_HEADER = "-- The CRUD hub's schema (db.py SCHEMA); generated by export_mock.py, do not edit by hand.\n"


def schema_sql():
    return SCHEMA_HEADER + "".join(s + ";\n" for s in db.ddl())


def export(root=ROOT):
    written = []
    for project, tables in snapshots().items():
        folder = os.path.join(root, project, "mock")
        if not os.path.isdir(os.path.dirname(folder)):
            continue
        os.makedirs(folder, exist_ok=True)
        lines = []
        for table, (rows, note) in tables.items():
            write_json(os.path.join(folder, f"{table}.json"), rows)
            lines.append(f"| `{table}.json` | {len(rows)} | {note} |")
            written.append((project, table, len(rows)))
        with open(os.path.join(folder, "schema.sql"), "w", encoding="utf-8", newline="\n") as f:
            f.write(schema_sql())
        lines.append(f"| `schema.sql` | {len(db.SCHEMA)} tables | the hub's CREATE TABLE statements |")
        with open(os.path.join(folder, "README.md"), "w", encoding="utf-8", newline="\n") as f:
            f.write(README.format(rows="\n".join(lines)))
    return written


if __name__ == "__main__":
    for project, table, n in export():
        print(f"{project}/mock/{table}.json  {n}")

